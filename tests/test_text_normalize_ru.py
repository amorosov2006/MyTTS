@pytest.mark.parametrize("text,expected", CASES)
def test_normalize_ru_golden(text, expected):
    assert normalize(text) == expected


def test_normalize_ru_idempotent():
    for text, expected in CASES:
        assert normalize(expected) == expected


# The exact prose used for the Phase 0 listening test / benchmark: make sure
# normalize() doesn't choke on it and doesn't touch it destructively (it's
# already hand-written in "spoken" form, no digits to convert).
@pytest.mark.parametrize("text", TRAPS_RU)
def test_normalize_ru_traps_dont_crash(text):
    result = normalize(text)
    assert result
    assert not result.isspace()


def test_traps_ru_money_and_abbrev_trap():
    result = normalize(TRAPS_RU[0])
    assert "тысяча восемьсот девяносто первом" in result
    assert "три дома" in result
    assert "две тысячи пятьсот рублей" in result
    assert "1891" not in result
    assert "2500" not in result


def test_traps_ru_yo_trap_restores_yo():
    result = normalize(TRAPS_RU[2])
    assert "ещё" in result


def test_traps_ru_latin_words_untouched():
    result = normalize(TRAPS_RU[3])
    assert "Windows" in result
    assert "Google" in result
